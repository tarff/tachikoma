describe("split", () => {
  it.each(TABLE)("%s: %j", (shell, line, expected) => {
    const result = split(line, shell);
    if (typeof expected === "string") expect(result).toEqual({ unreadable: expected });
    else expect("commands" in result ? result.commands.map((c) => c.words) : result).toEqual(expected);
  });

  // Choice 39: PowerShell's .NET calls that only read or compute stay readable.
  it.each([
    "[Math]::Round(1.5)",
    "[DateTime]::Now",
    "[IO.Path]::Combine('a','b')",
    "[System.IO.Path]::GetFileName($p)",
    "[Environment]::GetEnvironmentVariable('X')",
    "[Environment]::NewLine",
    '"$([DateTime]::Now)"',
    "[System.Math]::Max(1, 2)",
    "[IO.File]::ReadAllText('x.txt')",
    "[string]::Join(',', $a)",
    "[regex]::Escape($s)",
    "[Text.Encoding]::UTF8.GetBytes('x')",
    "[int]$x + 1",
    "$x.ToString()",
    "Get-ChildItem Microsoft.PowerShell.Core\\FileSystem::C:\\x",
    "[int]'5'",
    "[datetime]'2026-01-01'",
    "[version]'1.2'",
    "[uri]'https://x'",
    "[bool]'true'",
    "[System.Guid]'00000000-0000-0000-0000-000000000000'",
    "[Console]::OutputEncoding = [Text.Encoding]::UTF8",
    "[Console]::WriteLine('x')",
    "[System.Collections.Generic.List[string]]::new()",
    "[Collections.Generic.Dictionary[string,int]]::new()",
    "[System.Text.StringBuilder]::new()",
    "[IO.Directory]::GetFiles('.')",
    "[Diagnostics.Stopwatch]::StartNew()",
    "[System.TimeZoneInfo]::ConvertTimeBySystemTimeZoneId([datetime]::UtcNow, 'UTC')",
    "[TimeZoneInfo]::Local",
    "[TimeZoneInfo]::FindSystemTimeZoneById('UTC')",
    "[datetime]::ParseExact('x', 'y', $null)",
  ])("reads the PowerShell line %s", (line) => {
    expect("commands" in split(line, "powershell")).toBe(true);
  });

  it("reads the commands in a PowerShell string's method call", () => {
    const result = split("'x'.Replace((rm y), 'z')", "powershell");
    expect("commands" in result && result.commands.some((c) => c.words.join(" ") === "rm y")).toBe(true);
    expect(split("[IO.File]::WriteAllText('x', 'y')", "powershell")).toEqual({ unreadable: "a way of running text the check does not follow" });
  });

  it("says when brackets are nested too deep to read, rather than failing", () => {
    expect(split(`echo ${"$(".repeat(3000)}x${")".repeat(3000)}`, "bash")).toEqual({ unreadable: "nesting too deep for the check to read" });
  });

  it("gives each command's text as written, so a warning can show it", () => {
    const texts = (line: string, shell: Shell) => {
      const result = split(line, shell);
      return "commands" in result ? result.commands.map((c) => c.text) : result;
    };
    expect(texts("FOO=1 rm -rf ~ > out.txt && ls", "bash")).toEqual(["FOO=1 rm -rf ~ > out.txt", "ls"]);
    expect(texts("echo $(date  -u)", "bash")).toEqual(["echo $(date  -u)", "date  -u"]);
    expect(texts("bash -c 'a  x && b'", "bash")).toEqual(["bash -c 'a  x && b'", "a  x", "b"]);
    expect(texts("env -i rm -rf  ~ 2>&1", "bash")).toEqual(["env -i rm -rf  ~ 2>&1", "rm -rf  ~"]);
    expect(texts('for f in x; do rm "$f"; done', "bash")).toEqual(["for f in x", 'rm "$f"']);
    expect(texts("& 'git' status", "powershell")).toEqual(["'git' status"]);
  });
});

